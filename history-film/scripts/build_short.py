#!/usr/bin/env python3
"""Cuts the Short's voiceover from the finished Part 1 voiceover and writes its timing file."""
import json, subprocess, wave, os
import numpy as np
FF = "node_modules/@remotion/compositor-linux-x64-gnu/ffmpeg"
SR = 44100
D = json.load(open("public/evidence-room-1/units.json")); U = {u["id"]: u for u in D["units"]}
subprocess.run([FF, "-y", "-loglevel", "error", "-i", "public/evidence-room-1/voiceover.mp3", "-ar", str(SR), "-ac", "1", "out/_vo.wav"], check=True)
w = wave.open("out/_vo.wav"); a = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
# order of lines in the Short, with the pause (seconds) after each
SEQ = [("u2", .6), ("u8", .3), ("u10", .8), ("u11", .4), ("u13", .4), ("u14", .8), ("u27", .5), ("u28", 0.0)]
LEAD, TAIL = 0.5, 4.0
parts = [np.zeros(int(LEAD * SR), dtype=np.float32)]; t = LEAD; out = {}
for uid, gap in SEQ:
    u = U[uid]; x = a[int((u["start"] - .02) * SR): int((u["end"] + .08) * SR)].copy()
    f = int(.012 * SR); x[:f] *= np.linspace(0, 1, f); x[-f:] *= np.linspace(1, 0, f)
    out[uid] = [round(t + .02, 3), round(t + .02 + (u["end"] - u["start"]), 3)]
    parts += [x, np.zeros(int(gap * SR), dtype=np.float32)]; t += len(x) / SR + gap
parts.append(np.zeros(int(TAIL * SR), dtype=np.float32)); t += TAIL
audio = np.concatenate(parts)
with wave.open("out/_short.wav", "wb") as o:
    o.setnchannels(1); o.setsampwidth(2); o.setframerate(SR); o.writeframes((np.clip(audio, -1, 1) * 32767).astype(np.int16).tobytes())
subprocess.run([FF, "-y", "-loglevel", "error", "-i", "out/_short.wav", "-codec:a", "libmp3lame", "-b:a", "192k", "public/evidence-room-1/short-voiceover.mp3"], check=True)
os.remove("out/_vo.wav"); os.remove("out/_short.wav")
hit = out["u28"][0] + 4.2  # "Not proven" lands about 4.2 s into the verdict line
ts = f"""// Timing for the Short (seconds). Generated by scripts/build_short.py from the Part 1 voiceover.
export const SHORT_VOICEOVER = "evidence-room-1/short-voiceover.mp3";
export const SHORT_SECONDS = {round(t, 2)};
export const LINES = {json.dumps(out)} as const;
export const VERDICT_HIT = {round(hit, 2)};
// Scene cuts (hard cuts between comic pages)
export const SCENES = {{
  s1: [0, {round(out['u8'][0] - .25, 2)}],
  s2: [{round(out['u8'][0] - .25, 2)}, {round(out['u11'][0] - .3, 2)}],
  s3: [{round(out['u11'][0] - .3, 2)}, {round(out['u27'][0] - .3, 2)}],
  s4: [{round(out['u27'][0] - .3, 2)}, {round(t, 2)}],
}} as const;
"""
open("src/films/evidence-room-short-1/timing.ts", "w").write(ts)
print("short seconds", round(t, 1), out)
