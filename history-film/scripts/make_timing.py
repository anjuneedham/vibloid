#!/usr/bin/env python3
"""Writes src/films/evidence-room-1/timing.ts from public/evidence-room-1/units.json (output of build_vo.py)."""
import json
D = json.load(open("public/evidence-room-1/units.json"))
U = {u["id"]: u for u in D["units"]}
def s(i): return U[i]["start"]
def e(i): return U[i]["end"]
def m(i, raw):  # raw recording time -> final audio time
    u = U[i]; return u["start"] + (raw - u["src"][0][0]) / u["tempo"]

LEAD = 0.5
first = {1: "u1", 2: "u3", 3: "u6", 4: "u11", 5: "u18", 6: "u20", 7: "u26", 8: "u27", 9: "u31"}
start = {b: (0.0 if b == 1 else round(s(u) - LEAD, 2)) for b, u in first.items()}
END_CARD = 12.0
end = {b: start[b + 1] for b in range(1, 9)}
end[9] = round(start[9] + END_CARD, 2)
L = {b: end[b] - start[b] for b in start}

def f(b, t): return round(min(max((t - start[b]) / L[b], 0), 1), 4)
def sp(b, a, z): return [f(b, a), f(b, z)]
def tail(b, a): return [f(b, a), 1.0]

C = {}
C["b1"] = dict(pA=0, title=f(1, .5), l1=sp(1, s("u1") - .2, e("u1") + .6), pB=f(1, (s("u1") + e("u1")) / 2),
               l2=sp(1, s("u2") - .2, e("u2") + .8), pC=f(1, e("u2") + .3), hit=f(1, e("u2") + 1.5))
ch = m("u4", 27.4)
C["b2"] = dict(pA=0, d1=sp(2, s("u3") - .15, e("u3") + .5), pB=f(2, s("u4") - .4),
               seeds=f(2, m("u4", 27.5)), d2a=sp(2, s("u4") - .15, ch + .1), d2b=sp(2, ch + .1, e("u4") + .8),
               counter=f(2, m("u4", 29.6)), pC=f(2, e("u4") + .3), stamp=f(2, s("u5") + .4), cap=tail(2, s("u5") - .1))
C["b3"] = dict(pA=0, card=f(3, start[3] + .4), c1a=sp(3, s("u6") - .15, e("u6") + .3), marker=f(3, m("u6", 48.0)),
               c1b=sp(3, s("u7") - .1, e("u7") + .8), years=f(3, m("u7", 52.9)), pB=f(3, s("u8") - .5),
               d1=sp(3, s("u8") - .1, e("u9") + .9), pC=f(3, s("u10") - .6), o1=tail(3, s("u10") - .1))
C["b4"] = dict(pA=0, c1a=sp(4, s("u11") - .15, e("u11") + .3), c1b=sp(4, s("u12") - .15, e("u12") + .4),
               pB=f(4, s("u13") - .5), d1=sp(4, s("u13") - .1, e("u13") + .4), o1=sp(4, s("u14") - .1, e("u14") + .4),
               c2a=sp(4, s("u15") - .15, e("u16") + .4), pC=f(4, s("u16")), c2b=tail(4, s("u17") - .1))
C["b5"] = dict(pA=0, o1=sp(5, s("u18") - .1, e("u18") + 1.2), pB=f(5, e("u18") - .6),
               cap=tail(5, s("u19") - .1), stamp=f(5, s("u19") + .9))
C["b6"] = dict(pA=0, c1a=sp(6, s("u20") - .15, e("u20") + .3), c1b=sp(6, s("u21") - .1, e("u21") + .5),
               pB=f(6, s("u22") - .5), d1=sp(6, s("u22") - .1, e("u22") + .6), steam=f(6, m("u22", 158.3)),
               pC=f(6, s("u23") - .5), o1=sp(6, s("u23") - .1, e("u23") + .6), pD=f(6, s("u24") - .5),
               c2a=sp(6, s("u24") - .1, e("u24") + .3), c2b=tail(6, s("u25") - .1))
d1_, c_, h_ = m("u26", 196.24), m("u26", 198.7), m("u26", 197.0)
C["b7"] = dict(pA=0, cl1=sp(7, s("u26") - .2, d1_ + .3), card1=f(7, s("u26") - .3), stamp1=f(7, d1_ + .1),
               cl2=sp(7, h_ - .1, c_ + .3), card2=f(7, h_ - .1), stamp2=f(7, c_),
               cl3=tail(7, m("u26", 199.42) - .1), card3=f(7, m("u26", 199.42) - .1), stamp3=f(7, e("u26") - .2))
C["b8"] = dict(pA=0, c1a=sp(8, s("u27") - .15, e("u27") + .4), pB=f(8, s("u28") - .3),
               c1b=sp(8, s("u28") - .1, e("u28") + 1.0), hit=f(8, e("u28") - .1), pC=f(8, s("u29") - .5),
               d1=sp(8, s("u29") - .1, e("u29") + .6), pD=f(8, s("u30") - .5), o1=tail(8, s("u30") - .1),
               pushFrom=0.0, pushTo=1.0)
C["b9"] = dict(pA=0, c1a=sp(9, s("u31") - .15, e("u31") + .6), pB=f(9, start[9] + .6), pC=f(9, start[9] + 1.4),
               c1b=tail(9, e("u31") + .9), hit=f(9, e("u31") + .9))

titles = {1: "THE CASE", 2: "THE CLAIM", 3: "THE DATE", 4: "THE HAIR", 5: "THE NUMBERS", 6: "THE GREEK WITNESS",
          7: "THE EVIDENCE BOARD", 8: "THE VERDICT", 9: "NEXT CASE + END CARD"}
def fmt(v): return json.dumps(v)
beats = "\n".join(f'  b{b}: {{ title: "{titles[b]}", start: {start[b]}, end: {end[b]} }},' for b in range(1, 10))
cues = "\n".join("  b%d: {\n%s\n  }," % (b, "\n".join(f"    {k}: {fmt(v)}," for k, v in C[f"b{b}"].items())) for b in range(1, 10))

src = open("src/films/evidence-room-1/timing.ts").read()
a = src.index("export const BEATS")
b_ = src.index("export const BEAT_ORDER")
c = src.index("export const CUES")
d = src.index("export const cueFrame")
new = (src[:a] + "export const BEATS: Record<BeatId, { title: string; start: number; end: number }> = {\n" + beats + "\n};\n\n" +
       src[b_:c] + "export const CUES: Record<BeatId, Record<string, Cue>> = {\n" + cues + "\n};\n\n" + src[d:])
new = new.replace("export const HAS_VOICEOVER = false;", "export const HAS_VOICEOVER = true;")
new = new.replace("/** Beat start and end, in SECONDS, from script.md. */", "/** Beat start and end, in SECONDS, matched to the real voiceover (generated by scripts/make_timing.py). */")
open("src/films/evidence-room-1/timing.ts", "w").write(new)
print("total seconds", end[9], "frames", round(end[9] * 30))
